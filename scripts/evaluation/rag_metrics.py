"""Deterministic evidence metrics. Empty/missing results never become silent successes."""
import math
import re
import statistics


def normalize(text):
    return re.sub(r'\s+', '', text)


def evidence_key(chunk):
    match = re.search(r'(?m)^## ([^：:\n]+)[：:]', chunk['content'])
    if not match:
        raise ValueError('Retrieved chunk has no source-section identity')
    return chunk['source'].replace('\\', '/').split('/')[-1] + '#' + match[1].strip()


def retrieval_metrics(gold, ranked, k=5):
    if not gold:
        return None  # Unanswerable questions have no recall denominator.
    gold = set(gold)
    top = ranked[:k]
    # Count each logical section once even when several SKU copies are retrieved.
    return {'recallAt5': len(gold.intersection(top)) / len(gold),
            'hitAt5': float(bool(gold.intersection(top))),
            'mrrAt5': next((1 / i for i, key in enumerate(top, 1) if key in gold), 0.0)}


def score(case, response, trace, chunks):
    stages = trace['stages']
    rankings = [s for s in stages if s['stage'].endswith('.rerank')]
    if not rankings or response['result']['degraded']:
        raise ValueError('Incomplete or degraded RAG run')
    ranked = [evidence_key(chunks[c['chunkId']]) for c in rankings[-1]['output']]
    selected = response['selection']
    facts = response['factContext']['facts']
    chosen = [facts[i] for i in selected['factIds']]
    document_facts = {normalize(f['text']) for f in chosen if f['source'] != 'catalog'}
    required = {normalize(f) for f in case['requiredFacts']}
    optional = {normalize(f) for f in case.get('optionalFacts', [])} if case.get('labelVersion') == 2 else set()
    allowed = required | optional
    # Canonical paragraphs match the server's extractive answer contract exactly.
    # No judge model infers correctness from the text generated by the tested model.
    coverage = len(required & document_facts) / len(required) if required else None
    precision = len(allowed & document_facts) / len(document_facts) if document_facts else None
    insufficient = selected['insufficient']
    if case['answerable']:
        quality = required <= document_facts and document_facts <= allowed and not insufficient
    else:
        quality = insufficient and not document_facts
    result = {'retrieval': retrieval_metrics(case['goldEvidence'], ranked),
            'initialRetrieval': retrieval_metrics(case['goldEvidence'],
                [evidence_key(chunks[c['chunkId']]) for c in rankings[0]['output']]),
            'factCoverage': coverage, 'selectedFactPrecision': precision,
            'answerPass': quality, 'insufficient': insufficient,
            'rewriteTriggered': any(s['stage'] == 'rewrite' for s in stages),
            'rankedEvidence': ranked, 'returnedCandidateCount': len(rankings[-1]['input']),
            'retrievalMs': sum(s['elapsedMs'] for s in stages if s['stage'].endswith('.retrieval'))}
    if case.get('labelVersion') == 2:
        result.update(strictAnswerPass=(required == document_facts and not insufficient) if case['answerable']
                      else quality, optionalFactCount=len(document_facts & optional),
                      forbiddenFactCount=len(document_facts - allowed),
                      requiredContextCoverage=len(required & {normalize(f['text']) for f in facts if f['source']!='catalog'})/len(required)
                      if required else None)
    return result


def percentile(values, fraction):
    return sorted(values)[max(0, math.ceil(len(values) * fraction) - 1)] if values else None


def summarize(rows, cases, modes):
    summaries = {}
    for mode in modes:
        actual = {r['caseId']: r for r in rows if r['mode'] == mode and not r.get('warmup')}
        if len(actual) != sum(r['mode'] == mode and not r.get('warmup') for r in rows):
            raise ValueError('Repeated case/mode attempts require an explicit new run')
        planned = {c['id']: c for c in cases}
        if actual.keys() - planned.keys():
            raise ValueError('Unknown case result')
        answerable = [c for c in cases if c['answerable']]
        unanswerable = [c for c in cases if not c['answerable']]
        valid = [r for r in actual.values() if 'score' in r]
        def average_metric(key):
            return sum(actual.get(c['id'], {}).get('score', {}).get('retrieval', {}).get(key, 0)
                       for c in answerable) / len(answerable) if answerable else None
        all_latencies = [r['clientMs'] for r in actual.values()]
        success_latencies = [r['clientMs'] for r in valid]
        summaries[mode] = {'planned': len(cases), 'attempted': len(actual), 'valid': len(valid),
            'failed': len(actual) - len(valid), 'notAttempted': len(cases) - len(actual),
            **{key: average_metric(key) for key in ('recallAt5', 'hitAt5', 'mrrAt5')},
            'answerPassCount': sum(r['score']['answerPass'] for r in valid),
            'answerPassRate': sum(r['score']['answerPass'] for r in valid) / len(cases),
            'factCoverage': sum(actual.get(c['id'], {}).get('score', {}).get('factCoverage', 0) or 0
                                for c in answerable) / len(answerable) if answerable else None,
            'selectedFactPrecision': sum(actual.get(c['id'], {}).get('score', {}).get('selectedFactPrecision', 0) or 0
                                        for c in answerable) / len(answerable) if answerable else None,
            'correctAbstentionRate': sum(actual.get(c['id'], {}).get('score', {}).get('answerPass', False)
                                         for c in unanswerable) / len(unanswerable) if unanswerable else None,
            'falseAbstentionRate': sum(actual.get(c['id'], {}).get('score', {}).get('insufficient', False)
                                      for c in answerable) / len(answerable) if answerable else None,
            'rewriteTriggered': sum(r['score']['rewriteTriggered'] for r in valid),
            'meanCandidateCount': statistics.mean(r['score']['returnedCandidateCount'] for r in valid)
                                  if valid else None,
            'p50Ms': statistics.median(success_latencies) if success_latencies else None,
            'p95Ms': percentile(success_latencies, .95),
            'allAttemptsP95Ms': percentile(all_latencies, .95),
            'qualityScope': 'source-paragraph coverage + relevance + abstention, not independently human-labelled semantic accuracy'}
        if all(c.get('labelVersion') == 2 for c in cases):
            summaries[mode].update(
                strictAnswerPassRate=sum(r['score']['strictAnswerPass'] for r in valid)/len(cases),
                casesWithOptionalFacts=sum(r['score']['optionalFactCount']>0 for r in valid),
                casesWithForbiddenFacts=sum(r['score']['forbiddenFactCount']>0 for r in valid),
                qualityScope='v2 required fact coverage + optional fact allowance + forbidden fact exclusion + abstention; not human semantic accuracy')
    return summaries
